-- Q10. Журнал аудиту змін (останні 20 подій)
-- Питання: Які зміни були внесені в базу даних останніми?
-- ---------------------------------------------------------------------------
-- Питання користувача: Покажи останні 20 записів журналу аудиту.
SELECT id,
       action,
       table_name,
       record_id,
       old_values,
       new_values,
       changed_at
