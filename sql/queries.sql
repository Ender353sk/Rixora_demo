ORDER  BY ts DESC;

-- Опис: Факти, створені не в контексті конкретного чату.
-- Очікуваний результат: список глобальних фактів.

-- ---------------------------------------------------------------------------
-- Q17. Останнє повідомлення кожного чату (через представлення v_last_message)
-- Питання: Яке останнє повідомлення в кожному чаті?
-- ---------------------------------------------------------------------------
-- Питання користувача: Покажи останнє повідомлення кожного чату.
SELECT c.id,
       c.title,
       vm.last_text,
       vm.last_role,
       vm.last_ts
FROM   chats AS c
LEFT   JOIN v_last_message AS vm ON vm.chat_id = c.id
ORDER  BY vm.last_ts DESC;

-- Опис: Об'єднання чатів з представленням останніх повідомлень.
-- Очікуваний результат: кожен чат з текстом і роллю останнього повідомлення.

-- ---------------------------------------------------------------------------
-- Q18. Чати з найбільшою кількістю повідомлень (TOP 5)
-- Питання: П'ять чатів з найбільшою кількістю повідомлень.
-- ---------------------------------------------------------------------------
