-- ---------------------------------------------------------------------------
-- Q5. Статистика фактів по всіх чатах (представлення v_fact_stats)
-- Питання: Скільки фактів у кожному чаті і коли був останній додано?
-- ---------------------------------------------------------------------------
-- Питання користувача: Покажи статистику фактів по чатах.
SELECT chat_id,
       fact_count,
       last_fact_ts
FROM   v_fact_stats
ORDER  BY fact_count DESC;

-- Опис: Використовує представлення v_fact_stats для агрегованої статистики.
