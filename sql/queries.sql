-- ---------------------------------------------------------------------------
-- Q1. Список всіх чатів (останні першими) — для панелі історії UI
-- Питання: Які чати існують у системі, відсортовані за активністю?
-- ---------------------------------------------------------------------------
-- Питання користувача: Покажи список чатів, відсортованих за останнім оновленням.
SELECT c.id,
       c.title,
       c.created_at,
       c.updated_at,
       c.message_count,
       vm.last_text,
       vm.last_role
FROM   chats AS c
LEFT   JOIN v_last_message AS vm ON vm.chat_id = c.id
ORDER  BY c.updated_at DESC;

-- Опис: Повертає список чатів з останнім повідомленням кожного.
-- Використовується представлення v_last_message для отримання останнього тексту.
-- Очікуваний результат: таблиця чатів з колонками id, title, created_at,
-- updated_at, message_count, last_text, last_role.

-- ---------------------------------------------------------------------------
-- Q2. Повідомлення конкретного чату (хронологічний порядок)
-- Питання: Які повідомлення є в чаті з id = 'chat-123'?
-- ---------------------------------------------------------------------------
-- Питання користувача: Покажи всі повідомлення чату 'chat-123' у порядку надходження.
SELECT id,
       role,
       text,
       ts,
       order_index
FROM   messages
WHERE  chat_id = 'chat-123'
ORDER  BY order_index ASC;

-- Опис: Вибірка повідомлень чату за хронологічним індексом.
-- Очікуваний результат: список повідомлень з ролями user/model.

-- ---------------------------------------------------------------------------
-- Q3. Середньострокова свідка чату
-- Питання: Яка свідка збережена для чату 'chat-123'?
-- ---------------------------------------------------------------------------
-- Питання користувача: Покажи свідку середньострокової пам'яті для чату 'chat-123'.
SELECT chat_id,
