-- ---------------------------------------------------------------------------
-- Q4. Довгострокові факти по чату
-- Питання: Які факти довгострокової пам'яті належать чату 'chat-123'?
-- ---------------------------------------------------------------------------
-- Питання користувача: Покажи всі довгострокові факти чату 'chat-123'.
SELECT id,
       text,
       chat_id,
       msg_id,
       ts,
