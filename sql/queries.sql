-- Q16. Пошук фактів без привязки до чату (глобальні факти)
-- Питання: Які факти не привязані до жодного чату (chat_id IS NULL)?
-- ---------------------------------------------------------------------------
-- Питання користувача: Покажи всі факти без привязки до чату.
SELECT id,
       text,
       ts
FROM   ltm_facts
