-- ---------------------------------------------------------------------------
-- Q15. Факти за інтервалом часу (останні 7 днів)
-- Питання: Які факти були додані за останній тиждень?
-- ---------------------------------------------------------------------------
-- Питання користувача: Покажи факти, додані за останні 7 днів.
SELECT id,
       text,
       chat_id,
       ts
FROM   ltm_facts
WHERE  ts >= strftime('%s', 'now', '-7 days') * 1000
ORDER  BY ts DESC;

-- Опис: Фільтрація фактів за часові інтервали (unix ms).
-- Очікуваний результат: факти за останній тиждень.

