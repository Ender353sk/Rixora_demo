-- SQLite не має вбудованої системи ролей GRANT/REVOKE як PostgreSQL.
-- Реалізація прав доступу здійснюється на двох рівнях:
-- 1) Таблиця access_roles — оголошення ролей і їх прав (can_read, can_write, can_admin)
-- 2) Логіка на боку додатку (SqliteMemoryRepository / NetworkManager) — перевірка
--    ролі поточного користувача перед виконанням операцій.
-- Це альтернативний спосіб реалізації прав доступу, дозволений викладачем для SQLite.

-- ---------------------------------------------------------------------------
-- Таблиця access_roles (створюється у схемі)
-- Стовпці: id, role_name, can_read, can_write, can_admin
-- ---------------------------------------------------------------------------

-- Початкові ролі (вставляються у схемі):
--   reader  — може лише читати дані (SELECT)
--   writer  — може читати і писати (SELECT, INSERT, UPDATE, DELETE)
--   admin   — повний доступ, включаючи зміну структури та управління ролями

-- ---------------------------------------------------------------------------
-- Матриця доступу (документація)
-- ============================================================================
-- Об'єкт або дія           | reader | writer | admin
-- ============================================================================
-- Перегляд чатів (SELECT chats)           | Так    | Так    | Так
-- Перегляд повідомлень (SELECT messages)  | Так    | Так    | Так
-- Перегляд фактів (SELECT ltm_facts)      | Так    | Так    | Так
-- Перегляд свідки (SELECT chat_memory)    | Так    | Так    | Так
-- Перегляд аудиту (SELECT audit_log)      | Ні     | Ні     | Так
-- Додавання чату (INSERT chats)           | Ні     | Так    | Так
-- Додавання повідомлення (INSERT messages)| Ні     | Так    | Так
-- Додавання факту (INSERT ltm_facts)      | Ні     | Так    | Так
-- Оновлення чату (UPDATE chats)           | Ні     | Так    | Так
-- Видалення повідомлення (DELETE messages)| Ні     | Так    | Так
-- Видалення чату (DELETE chats)           | Ні     | Ні     | Так
-- Видалення всіх чатів (DELETE ALL)       | Ні     | Ні     | Так
-- Зміна структури таблиць (ALTER/DROP)    | Ні     | Ні     | Так
-- Зміна ролей доступу                     | Ні     | Ні     | Так
-- Резервне копіювання / відновлення       | Ні     | Ні     | Так
-- ============================================================================

