-- ============================================================================
-- Резервне копіювання та відновлення бази даних (SQLite)
-- Підсистема довготривалої пам'яті Ріксори
-- Курсова робота з дисципліни «Бази даних»
-- ============================================================================

-- SQLite не має pg_dump/pg_restore як PostgreSQL. Резервне копіювання здійснюється
-- через копіювання файлу бази даних або через логічний дамп (SQL-скрипт).
-- У репозиторії реалізовано методи backupDatabase() і restoreDatabase().

-- ---------------------------------------------------------------------------
-- Спосіб 1: Файлове резервне копіювання (рекомендовано для SQLite)
-- ---------------------------------------------------------------------------
-- База даних — це один файл (rixora_memory.db). Резервна копія — це його копія.
-- У коді C++ (SqliteMemoryRepository::backupDatabase):
--
--   QFile dbFile(m_db.databaseName());   // шлям до поточної БД
--   dbFile.copy(backupPath);             // копія у резервний файл
--
-- Приклад командного рядка (cmd / PowerShell):
--
--   copy "D:\Rixora_demo\RixoraAI_UI_Qt\rixora_memory.db" "backup_rixora_20261121.db"
--
-- Або через sqlite3 утиліту:
--
--   sqlite3 rixora_memory.db ".backup backup_rixora.db"

-- ---------------------------------------------------------------------------
-- Спосіб 2: Логічний дамп (SQL-скрипт)
-- ---------------------------------------------------------------------------
-- Створення дампу (всі таблиці, дані, схему):
--
--   sqlite3 rixora_memory.db ".dump" > rixora_memory_dump.sql
--
-- Відновлення з дампу:
--
--   sqlite3 rixora_memory_restore.db < rixora_memory_dump.sql

-- ---------------------------------------------------------------------------
-- Спосіб 3: SQL CLI .backup (онлайн-копія без блокування)
-- ---------------------------------------------------------------------------
--   sqlite3 rixora_memory.db ".backup online_backup.db"

-- ---------------------------------------------------------------------------
-- Протокол перевірки відновлення (за методичними рекомендациями розділ 5.10)
-- ---------------------------------------------------------------------------
-- Крок 1: Створити резервну копію поточної бази даних.
-- Крок 2: Створити порожню тестову базу (createdb еквівалент — новий файл .db).
-- Крок 3: Відновити дані з резервної копії у тестову базу.
-- Крок 4: Перевірити:
--   a) Наявність таблиць: chats, messages, chat_memory, ltm_facts, audit_log, access_roles, ...
--   b) Наявність ключів, індексів, функцій, тригерів, представлень.
--   c) Кількість рядків і контрольні підсумки (COUNT по ключових таблицях).
--   d) Результат основних запитів (список чатів, факти, свідки).
--   e) Ролі та права доступу (таблиця access_roles).
-- Крок 5: Порівняти контрольні суми з оригінальною базою.

-- ---------------------------------------------------------------------------
-- SQL-скрипт перевірки контрольних сум після відновлення
-- ---------------------------------------------------------------------------

-- Кількість рядків по основних таблицях:
SELECT 'chats' AS table_name, COUNT(*) AS row_count FROM chats
UNION ALL
SELECT 'messages', COUNT(*) FROM messages
UNION ALL
SELECT 'chat_memory', COUNT(*) FROM chat_memory
UNION ALL
SELECT 'ltm_facts', COUNT(*) FROM ltm_facts
UNION ALL
SELECT 'audit_log', COUNT(*) FROM audit_log
UNION ALL
SELECT 'access_roles', COUNT(*) FROM access_roles;

-- Перевірка індексів:
SELECT name, tbl_name FROM sqlite_master WHERE type = 'index' ORDER BY tbl_name;

-- Перевірка тригерів:
SELECT name, tbl_name FROM sqlite_master WHERE type = 'trigger' ORDER BY tbl_name;

-- Перевірка представлень:
SELECT name FROM sqlite_master WHERE type = 'view' ORDER BY name;

-- Перевірка ролей:
SELECT role_name, can_read, can_write, can_admin FROM access_roles;

-- ---------------------------------------------------------------------------
-- Обмеження порівняно з PostgreSQL
-- ---------------------------------------------------------------------------
-- | Аспект               | PostgreSQL                          | SQLite (поточне рішення)        |
-- |----------------------|-------------------------------------|----------------------------------|
-- | Інструмент резерву   | pg_dump / pg_restore               | Копіювання .db файлу / .backup   |
-- | Відновлення          | pg_restore у нову базу             | Копіювання файлу / импорт дампу  |
-- | Логічноє копіювання  | Підтримується                      | Через .dump SQL-скрипт           |
-- | фізичне копіювання   | Базове резервування кластера       | Один файл БД                     |
-- | Відновлення на момент часу | PITR через WAR                  | Не підтримується нативно         |
-- | Реплікація           | Потокова логічна реплікація        | Не підтримується нативно         |
-- ============================================================================
