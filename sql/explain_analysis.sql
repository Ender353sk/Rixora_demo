-- ============================================================================
-- Аналіз планів виконання запитів (EXPLAIN QUERY PLAN)
-- Підсистема довготривалої пам'яті Ріксори (SQLite)
-- Курсова робота з дисципліни «Бази даних»
-- ============================================================================
-- У SQLite замість PostgreSQL EXPLAIN (ANALYZE, BUFFERS) використовується
-- EXPLAIN QUERY PLAN, який показує статичний план без виконання запиту.
-- Для Negative/positiv порівняння потрібно набрати велику кількість даних.

-- ---------------------------------------------------------------------------
-- Крок 1: Акумуляція статистики ( аналог ANALYZE в PostgreSQL )
-- ---------------------------------------------------------------------------
-- SQLite автоматично зберігає статистику у sqlite_stat1 приrun ANALYZE.
ANALYZE;

-- ---------------------------------------------------------------------------
-- Крок 2: Порівняння планів для запиту пошуку повідомлень чату
-- ---------------------------------------------------------------------------

-- До додавання індексу (послідовне сканування):
EXPLAIN QUERY PLAN
SELECT id, role, text FROM messages WHERE chat_id = 'chat-123' ORDER BY order_index ASC;

-- Очікуваний план (без індексу):
-- SCAN messages
-- USE TEMP B-TREE FOR ORDER BY

-- Після додавання індексу idx_messages_chat_order (уже є в схемі):
EXPLAIN QUERY PLAN
SELECT id, role, text FROM messages WHERE chat_id = 'chat-123' ORDER BY order_index ASC;

-- Очікуваний план (з індексом):
-- SEARCH messages USING INDEX idx_messages_chat_order (chat_id=?)
--   (порядок індексу вже відповідає ORDER BY, додаткове сортування не потрібне)

-- ---------------------------------------------------------------------------
-- Крок 3: Порівняння планів для пошуку фактів по чату
-- ---------------------------------------------------------------------------

-- Пошук фактів без урахування індексу (якби індексу не було):
EXPLAIN QUERY PLAN
SELECT id, text, ts FROM ltm_facts WHERE chat_id = 'chat-123' ORDER BY ts DESC;

-- Очікуваний план (з індексом idx_ltm_facts_chat_id):
-- SEARCH ltm_facts USING INDEX idx_ltm_facts_chat_id (chat_id=?)
--   (збірка рядків, потім сортування за ts)

-- ---------------------------------------------------------------------------
-- Крок 4: Порівняння планів для пошуку останнього повідомлення (представлення)
-- ---------------------------------------------------------------------------

EXPLAIN QUERY PLAN
SELECT * FROM v_last_message WHERE chat_id = 'chat-123';

-- Очікуваний план:
-- SCAN m (підзапит)
-- SEARCH messages USING INDEX idx_messages_chat_id (chat_id=?)
--   SUBQUERY на messages з ORDER BY order_index DESC LIMIT 1

-- ---------------------------------------------------------------------------
-- Крок 5: Порівняння планів для LIKE-пошуку по тексту фактів
-- ---------------------------------------------------------------------------

EXPLAIN QUERY PLAN
SELECT id, text FROM ltm_facts WHERE text LIKE '%проєкт%';

-- Очікуваний план:
-- SCAN ltm_facts
--   (повне сканування, тому що LIKE з '%' на початку не може використати індекс)
-- Примітка: Для прискорення такого пошуку потрібен FTS модуль SQLite.

-- ---------------------------------------------------------------------------
-- Крок 6: Порівняння планів для завантаження свідки чату
-- ---------------------------------------------------------------------------

EXPLAIN QUERY PLAN
SELECT mid_term_summary FROM chat_memory WHERE chat_id = 'chat-123';

-- Очікуваний план:
-- SEARCH chat_memory USING PRIMARY KEY (chat_id=?)
--   (SHUTDOWN через первинний ключ, O(1) доступ)

-- ---------------------------------------------------------------------------
-- Крок 7: Порівняння планів для отримання списку чатів (останні першими)
-- ---------------------------------------------------------------------------

EXPLAIN QUERY PLAN
SELECT c.id, c.title, c.updated_at FROM chats c ORDER BY c.updated_at DESC;

-- Очікуваний план:
-- SCAN chats
-- USE TEMP B-TREE FOR ORDER BY
-- Примітка: можна додати індекс на chats(updated_at DESC) для прискорення.

-- ---------------------------------------------------------------------------
-- Крок 8: Таблиця порівняння (для протоколу дослідження продуктивності)
-- ---------------------------------------------------------------------------

-- Показник                    | До індексу     | Після індексу  | Коментар
-- ----------------------------|----------------|----------------|------------------------------------------
-- Версія СУБД                 | SQLite 3.x     | SQLite 3.x     | Одна версія
-- Обсяг таблиці messages      | 10 000 рядків  | 10 000 рядків  | Тестові дані
-- Параметри запиту            | chat_id='x'    | chat_id='x'    | Те самі значення
-- Основні вузли плану         | SCAN messages  | SEARCH USING INDEX | Індекс зменшує обсяг сканування
-- Фактичні рядки (approx)     | 10 000         | ~50 (к-сть повідомлень чату) | Суттєве зменшення
-- Execution Time (мс)         | вимірюється    | вимірюється    | Фактичні дані з лабораторії
-- Розмір індексу              | відсутній      | ~400 KB        | Впливає на дисковий простір

-- ---------------------------------------------------------------------------
-- Висновок з аналізу планів
-- ---------------------------------------------------------------------------
-- 1. Індекси на зовнішніх ключах (chat_id) суттєво прискорюють пошук
--    повідомлень і фактів по чаті.
-- 2. LIKE-пошук з '%' на початку не може використати B-дерево індексу —
--    для текстового пошуку потрібен FTS5 модуль SQLite.
-- 3. PRIMARY KEY на chats.id та chat_memory.chat_id дає O(1) доступ.
-- 4. Представлення v_last_message використовує підзапит з LIMIT 1, що
--    ефективне для отримання останнього повідомлення.
-- ============================================================================
