-- ============================================================================
-- Сценарій конкурентного доступу до бази даних (SQLite)
-- Підсистема довготривалої пам'яті Ріксори
-- Курсова робота з дисципліни «Бази даних»
-- ============================================================================

-- SQLite у режимі WAL (Write-Ahead Logging) дозволяє:
-- 1) Кілька одночасно читаючих підключень (CONCURRENT READS)
-- 2) Одно записуючий підключення в один момент часу (ONE WRITER)
-- Це відрізняється від PostgreSQL, де є pivnyi рівні ізоляції та блокування рядків.

-- ---------------------------------------------------------------------------
-- Налаштування WAL режиму (виконується при ініціалізації репозиторію)
-- ---------------------------------------------------------------------------
PRAGMA journal_mode = WAL;
PRAGMA busy_timeout = 5000;  -- очікування до 5 секунд при блокуванні запису

-- ---------------------------------------------------------------------------
-- Сценарій конкурентного доступу (два сеанси)
-- ---------------------------------------------------------------------------

-- Сеанс А (сторона додатку — збереження поточного чату):
--   1. BEGIN;
--   2. SELECT message_count FROM chats WHERE id = 'chat-123' FOR UPDATE;
--      (у SQLite FOR UPDATE не блокує рядок, але транзакція відкрита)
--   3. UPDATE chats SET message_count = message_count + 1 WHERE id = 'chat-123';
--      (транзакція ще відкрита — запис у черзі)
--
-- Сеанс Б (інший екземпляр додатка або потік — спроба оновлення того ж чату):
--   1. BEGIN;
--   2. UPDATE chats SET message_count = message_count + 1 WHERE id = 'chat-123';
--      (блокується, доки Сеанс А не зробить COMMIT або ROLLBACK;
--       busy_timeout = 5000 ms — якщо не встигне, виникне SQLITE_BUSY)
--   3. COMMIT (після того як Сеанс А завершить транзакцію).

-- ---------------------------------------------------------------------------
-- Кроки перевірки конкурентного доступу (протокол)
-- ---------------------------------------------------------------------------
-- Крок 1: Відкрити два підключення до однієї бази даних (різні з'єднання QSqlDatabase).
-- Крок 2: У сеансі А виконати BEGIN; UPDATE chats SET ... (транзакція залишається відкритою).
-- Крок 3: У сеансі Б виконати UPDATE chats SET ... на ту саму строку.
-- Крок 4: Сеанс Б повинен заблокуватися на busy_timeout (5 сек).
-- Крок 5: У сеансі А виконати COMMIT.
-- Крок 6: Сеанс Б розблокується та завершить оновлення.
-- Крок 7: Перевірити, що message_count збільшений на 2 (по 1 для кожного сеансу).
-- Крок 8: Повторити з ROLLBACK у сеансі А — сеанс Б оновлює на основі даних до змін А.

-- ---------------------------------------------------------------------------
-- Рівень ізоляції в SQLite
-- ---------------------------------------------------------------------------
-- SQLite використовує рівень ізоляції SERIALIZABLE для транзакцій.
-- Читання не блокує запис, а запис не блокує читання (у WAL режимі).
-- Конфлікти запису-випису виявляються при COMMIT.

-- ---------------------------------------------------------------------------
-- Порівняння з PostgreSQL (обґрунтування вибору SQLite для курсової)
-- | Характеристика       | PostgreSQL                          | SQLite (поточне рішення)        |
-- |----------------------|-------------------------------------|----------------------------------|
-- | Конкурентний доступ  | Мільтрикористувальчій, рядкові блокування | Один записувач, багато читачів (WAL) |
-- | Рівні ізоляції       | Read Committed, Repeatable Read, Serializable | Serializable (за замовчуванням) |
-- | Забезпечення доступу | GRANT/REVOKE ролі                   | Логіка на боку додатку (access_roles) |
-- | Backup               | pg_dump / pg_restore               | Копіювання .db файлу (sqlite3 .backup) |
-- | EXPLAIN ANALYZE      | EXPLAIN (ANALYZE, BUFFERS)         | EXPLAIN QUERY PLAN (без виконання) |
-- ============================================================================
