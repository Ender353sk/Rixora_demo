-- Т01: Додавання коректного чату (позитивний)
-- ---------------------------------------------------------------------------
-- Дія: INSERT INTO chats(id, title, created_at, updated_at, message_count)
--      VALUES ('chat-test-01', 'Тестовий чат', strftime('%s','now')*1000,
--              strftime('%s','now')*1000, 0);
-- Очікуваний результат: Рядок успішно вставлено. chatExists('chat-test-01') = 1.
-- Примітки: Перевірка основної операції створення чату.

-- ---------------------------------------------------------------------------
-- Т02: Додавання чату з порожнім заголовком (позитивний, DEFAULT '')
-- ---------------------------------------------------------------------------
-- Дія: INSERT INTO chats(id, title, created_at, updated_at, message_count)
--      VALUES ('chat-test-02', '', strftime('%s','now')*1000,
--              strftime('%s','now')*1000, 0);
-- Очікуваний результат: Рядок вставлено, title = '' (за замовчуванням NOT NULL).
-- Примітки: Перевірка обмеження NOT NULL на title.

-- ---------------------------------------------------------------------------
-- Т03: Повторне вставлення чату з тим же id (негативний, UNIQUE/PK порушення)
-- ---------------------------------------------------------------------------
-- Дія: INSERT INTO chats(id, title, created_at, updated_at, message_count)
--      VALUES ('chat-test-01', 'Дубль', strftime('%s','now')*1000,
--              strftime('%s','now')*1000, 0);
-- Очікуваний результат: Помилка UNIQUE constraint failed: chats.id.
-- Примітки: Первинний ключ musi бути унікальним.

-- ---------------------------------------------------------------------------
-- Т04: Додавання повідомлення з неіснуючим chat_id (негативний, FK порушення)
-- ---------------------------------------------------------------------------
-- Дія: INSERT INTO messages(id, chat_id, role, text, ts, order_index)
--      VALUES ('msg-test-01', 'nonexistent-chat', 'user', 'Текст',
--              strftime('%s','now')*1000, 0);
-- Очікуваний результат: Помилка FOREIGN KEY constraint failed.
-- Примітки: Зовнішній ключ messages.chat_id → chats.id з ON DELETE CASCADE.

-- ---------------------------------------------------------------------------
-- Т05: Додавання повідомлення з некоректною роллю (негативний, CHECK порушення)
-- ---------------------------------------------------------------------------
-- Дія: INSERT INTO messages(id, chat_id, role, text, ts, order_index)
--      VALUES ('msg-test-02', 'chat-test-01', 'admin', 'Текст',
--              strftime('%s','now')*1000, 0);
-- Очікуваний результат: Помилка CHECK constraint failed: role IN ('user', 'model').
-- Примітки: Роль має бути 'user' або 'model'.

-- ---------------------------------------------------------------------------
-- Т06: Додавання факту з текстом коротше 8 символів (негативний, тригер перевірки)
-- ---------------------------------------------------------------------------
-- Дія: INSERT INTO ltm_facts(text, chat_id, msg_id, ts, signature)
--      VALUES ('Коротко', 'chat-test-01', 'msg-test-01',
--              strftime('%s','now')*1000, 0);
-- Очікуваний результат: Помилка RAISE(ABORT, 'Текст факту занадто короткий...').
-- Примітки: Тригер trg_ltm_facts_before_insert_check блокує вставку.

-- ---------------------------------------------------------------------------
-- Т07: Додавання коректного факту (позитивний)
-- ---------------------------------------------------------------------------
-- Дія: INSERT INTO ltm_facts(text, chat_id, msg_id, ts, signature)
--      VALUES ('Користувач bevorzugує темну тему', 'chat-test-01', 'msg-test-01',
--              strftime('%s','now')*1000, 0);
-- Очікуваний результат: Рядок вставлено. factCount() збільшився на 1.
-- Примітки: Аудит-тригер trg_ltm_facts_insert_audit також спрацював.

-- ---------------------------------------------------------------------------
-- Т08: Видалення чату з повідомленнями (каскадне видалення через FK)
-- ---------------------------------------------------------------------------
-- Дія: DELETE FROM chats WHERE id = 'chat-test-01';
-- Очікуваний результат: Чатет видалено, всі пов'язані повідомлення видалені
-- каскадно (ON DELETE CASCADE), фактів також видалено (якщо були з цим chat_id).
-- Примітки: Перевірка каскадного видалення.

-- ---------------------------------------------------------------------------
-- Т09: Видалення датчика з залежними даними (замість цього — видалення чату
--      якщо є залежні факти LTM) (негативний через каскад)
-- ---------------------------------------------------------------------------
-- Дія: Спочатку додати факт з chat_id = 'chat-test-02', потім видалити чат 'chat-test-02'.
-- Очікуваний результат: Чат і його повідомлення видалені каскадно; факти з цим
-- chat_id також видаляються (багатьох-до-одного зв'язок).
-- Примітки: Каскадне видалення через всі FK на chats.id.

-- ---------------------------------------------------------------------------
-- Т10: Транзакція з відкатом (ROLLBACK)
-- ---------------------------------------------------------------------------
-- Дія: BEGIN;
--      INSERT INTO chats(...) VALUES ('chat-rollback', 'Тест', ...);
--      ROLLBACK;
--      SELECT COUNT(*) FROM chats WHERE id = 'chat-rollback';
-- Очікуваний результат: Результат COUNT = 0 (чату немає після відкату).
-- Примітки: Перевірка атомарності транзакції.

-- ---------------------------------------------------------------------------
-- Т11: Транзакція з підтвердженням (COMMIT)
