-- ---------------------------------------------------------------------------
-- Q6. Пошук фактів за текстом (лексичний, LIKE)
-- Питання: Знайди факти, які містять слово 'проєкт'.
-- ---------------------------------------------------------------------------
-- Питання користувача: Знайди всі довгострокові факти з текстом, що містить 'проєкт'.
SELECT id,
       text,
       chat_id,
       ts
FROM   ltm_facts
WHERE  text LIKE '%проєкт%'
ORDER  BY ts DESC
LIMIT  20;

-- Опис: Лексичний пошук за LIKE. Для повноцінного FTS потрібен додатковий модуль,
-- але LIKE достатній для демонстрації.
-- Очікуваний результат: факти, текст яких містить зазначений рядок.

-- ---------------------------------------------------------------------------
-- Q7. Останні N повідомлень з курсорною дозагрузкою (peek)
-- Питання: Останні 10 повідомлень чату 'chat-123', пропустивши останні 5.
-- ---------------------------------------------------------------------------
-- Питання користувача: Отримай останні 10 повідомлень чату 'chat-123' з пропуском 5 з кінця.
SELECT id,
       role,
       text,
       ts,
       order_index
FROM   messages
WHERE  chat_id = 'chat-123'
ORDER  BY order_index DESC
LIMIT  10 OFFSET 5;

-- Опис: Курсорна дозагрузка для поділу історії на сторінки.
-- Очікуваний результат: до 10 повідомлень, починаючи з 5-го з кінця.

-- ---------------------------------------------------------------------------
-- Q8. Чати без повідомлень (пусті чати)
-- Питання: Які чати не містять жодного повідомлення?
-- ---------------------------------------------------------------------------
-- Питання користувача: Покажи чати, у яких немає повідомлень.
SELECT c.id,
       c.title,
       c.created_at
FROM   chats AS c
LEFT   JOIN messages AS m ON m.chat_id = c.id
WHERE  m.id IS NULL;

-- Опис: LEFT JOIN з перевіркою на відсутність повідомлень.
-- Очікуваний результат: список порожніх чатів.

-- ---------------------------------------------------------------------------
-- Q9. Чи running fact extraction за сьогодні (ліміт API-викликів)
-- Питання: Скільки разів запускалася екстракція фактів сьогодні?
-- ---------------------------------------------------------------------------
-- Питання користувача: Покажи кількість запусків екстракції фактів за сьогодні.
SELECT COUNT(*) AS runs_today
FROM   extraction_runs
WHERE  run_at >= strftime('%s', 'now') * 1000
       AND run_at < strftime('%s', 'now') * 1000 + 86400000;

-- Опис: Підрахунок запусків екстракції за поточну добу.
-- Очікуваний результат: одне число — кількість запусків.

