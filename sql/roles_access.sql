// ---------------------------------------------------------------------------
-- Приклад перевірки прав у тестах:
-- ---------------------------------------------------------------------------
-- T01: Спроба читача виконати INSERT — очікується відмова в доступі.
-- T02: Письмо з ролі writer — очікується успіх.
-- T03: Спроба читача видалити чат — очікується відмова в доступі.
-- T04: Адміністратор може виконати будь-яку операцію — очікується успіх.

-- ---------------------------------------------------------------------------
-- Інструкція з перевірки прав у SQLite (через прикладну логіку):
-- ---------------------------------------------------------------------------
-- 1. Створити поточного користувача з роллю 'reader' (зберігається в сесії додатку).
-- 2. Спробувати виконати INSERT INTO ltm_facts(...) — додаток повинен відхилити
--    операцію, тому що can_read = 1, can_write = 0 для ролі reader.
-- 3. Змінити роль на 'writer' і повторити спробу — операція повинна успіти.
-- 4. Змінити роль на 'admin' і спробувати видалити чат — операція повинна успіти.

